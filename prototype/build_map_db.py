"""Build a fresh combined demo database without modifying an existing database.

python build_map_db.py --output crime-multicity.db
Add --geocode to query uncached block addresses sequentially (may be slow).
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import sqlite3
import tempfile

import geocode_city_pilot as geocoder
from load_db import connect, load_records, verify
from normalize import normalize
from normalize_city import normalize_records

ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'data'
CITY_BY_SOURCE = {
    'costa_mesa_police_incidents': 'Costa Mesa',
    'anaheimcrime_anaheim_incidents': 'Anaheim',
    'fullerton_police_calls_for_service': 'Fullerton',
}



def load_resolved():
    path=DATA/'geocoding'/'resolved-locations.json'
    if not path.exists():return {}
    selected={}
    for result in json.loads(path.read_text())['results']:
        # A matched city explicitly different from the source context needs
        # review, even when loading a manifest generated by an older version.
        if result.get('matched_city') and result['matched_city'].casefold()!=result['city_context'].casefold():
            continue
        key=(result['city_context'],result['original_location'])
        if key in selected:raise ValueError('Duplicate resolved location key')
        points=result.get('candidates',[])
        if result.get('status')!='candidate_needs_map_review' or len(points)!=1:
            raise ValueError('Resolved location has no unique accepted point')
        point=points[0]
        lat,lon=point.get('latitude'),point.get('longitude')
        if not(isinstance(lat,(int,float)) and isinstance(lon,(int,float)) and
               not isinstance(lat,bool) and not isinstance(lon,bool) and -90<=lat<=90 and -180<=lon<=180):
            raise ValueError('Invalid resolved location coordinates')
        if not point.get('checks') or not all(v is True for v in point['checks'].values()):
            raise ValueError('Resolved location has failing consistency checks')
        selected[key]=result
    return selected


def build(output, live=False):
    output = Path(output).resolve()
    if output.exists():
        raise FileExistsError(f'{output} already exists; choose a new output path')
    costa, held = normalize(json.loads((DATA / 'layer57.json').read_text()))
    if held:
        raise ValueError(f'Costa Mesa normalization held {len(held)} records')
    records = costa[:]
    for city, name in [('anaheim', 'anaheim-september-2026-raw.json'),
                       ('fullerton', 'fullerton-november-2026-raw.json')]:
        accepted, held = normalize_records(json.loads((DATA / name).read_text()), city)
        if held:
            raise ValueError(f'{city} normalization held {len(held)} records')
        records.extend(accepted)
    geocoder.ROOT = DATA / 'geocoding'
    lookups, provenance = load_resolved(), {}
    for record in records:
        city = CITY_BY_SOURCE[record['source']]
        if city == 'Costa Mesa':
            continue
        key = (city, record['location'])
        if key not in lookups:
            if key in geocoder.SAMPLES:
                index = geocoder.SAMPLES.index(key) + 1
            else:
                index = int(hashlib.sha256(repr(key).encode()).hexdigest()[:12], 16) + 100
            original = record['location'] or ''
            if not geocoder.re.fullmatch(r'(\d+) BLOCK (.+)', original):
                result = geocoder.resolve_block(city, original, None)
            else:
                result = geocoder.resolve_block(city, original,
                    geocoder.cached_fetch(index, original, cached_only=not live))
            lookups[key] = result
            if live:
                print(city, original, result['status'], flush=True)
        result = lookups[key]
        if result['status'] != 'candidate_needs_map_review':
            continue
        point = result['candidates'][0]
        record.update(latitude=point['latitude'], longitude=point['longitude'], location_precision=result.get('precision','block'))
        record['quality_flags'] = sorted((set(record['quality_flags']) - {'missing_coordinates'}) | {'location_not_exact'})
        provenance[(record['source'], record['source_record_id'])] = result
    output.parent.mkdir(parents=True, exist_ok=True)
    # All processing happens in a fresh temporary DB. Publish with an exclusive
    # hard link, so neither existing data nor a concurrent build is overwritten.
    with tempfile.TemporaryDirectory(dir=output.parent) as temp:
        staging = Path(temp) / 'combined.db'
        conn = connect(staging)
        try:
            summary = load_records(conn, records)
            if summary['held'] or verify(conn, records):
                raise ValueError('Combined database did not pass loader verification')
            with conn:
                for (source, identifier), result in provenance.items():
                    incident_id = conn.execute('SELECT id FROM incidents WHERE source=? AND source_record_id=?',
                                               (source, identifier)).fetchone()[0]
                    point = result['candidates'][0]
                    conn.execute('INSERT INTO incident_geocoding VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
                        (incident_id, result.get('provider','US Census Geocoder'), result['method'], result['original_location'],
                         result['selected_query_address'], result['city_context'], result['request_url'],
                         point['matched_address'], json.dumps(result['benchmark']), json.dumps(point['checks'])))
        finally:
            conn.close()
        output.hardlink_to(staging)
    total = Counter(CITY_BY_SOURCE[r['source']] for r in records)
    mapped = Counter(CITY_BY_SOURCE[r['source']] for r in records if r['latitude'] is not None)
    report = {'database': output.name, 'total_records': len(records),
              'mapped_records': sum(mapped.values()), 'by_city': {
                  city: {'total': count, 'mapped': mapped[city], 'unmapped': count-mapped[city]}
                  for city, count in total.items()},
              'block_lookup_statuses': dict(Counter(r['status'] for r in lookups.values()))}
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'crime-multicity.db')
    parser.add_argument('--geocode', action='store_true', help='Perform uncached live lookups; otherwise use saved matches only')
    args = parser.parse_args()
    try:
        report = build(args.output, args.geocode)
    except (OSError, ValueError, sqlite3.Error) as exc:
        parser.exit(1, str(exc) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
